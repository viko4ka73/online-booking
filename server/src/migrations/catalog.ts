import type { Pool } from "pg";

export async function migrateCatalog(pool: Pool) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock(73190351)");
    await client.query("CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())");
    const applied = await client.query("SELECT version FROM schema_migrations WHERE version = '001_catalog'");
    if (applied.rows.length) {
      await client.query("COMMIT");
      return;
    }
    await client.query(`
      CREATE TABLE sports (id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE);
      CREATE TABLE halls (id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE);
      CREATE TABLE courts (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        sport_id TEXT NOT NULL REFERENCES sports(id),
        hall_id TEXT NOT NULL REFERENCES halls(id),
        image TEXT NOT NULL,
        capacity SMALLINT NOT NULL CHECK (capacity > 0),
        description TEXT NOT NULL,
        dimensions TEXT NOT NULL,
        surface TEXT NOT NULL,
        equipment_description TEXT NOT NULL
      );
      CREATE TABLE equipment (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL
      );
      CREATE TABLE court_equipment (
        court_id INTEGER NOT NULL REFERENCES courts(id),
        equipment_id TEXT NOT NULL REFERENCES equipment(id),
        max_quantity SMALLINT NOT NULL CHECK (max_quantity > 0),
        PRIMARY KEY (court_id, equipment_id)
      );
      CREATE TABLE opening_hours (
        weekday SMALLINT PRIMARY KEY CHECK (weekday BETWEEN 0 AND 6),
        opens_at SMALLINT NOT NULL CHECK (opens_at >= 0 AND opens_at % 30 = 0),
        closes_at SMALLINT NOT NULL CHECK (closes_at <= 1440 AND closes_at % 30 = 0),
        CHECK (closes_at > opens_at)
      );
      CREATE TABLE reservation_equipment (
        reservation_id UUID NOT NULL REFERENCES court_reservations(id) ON DELETE CASCADE,
        equipment_id TEXT NOT NULL REFERENCES equipment(id),
        equipment_name TEXT NOT NULL,
        quantity SMALLINT NOT NULL CHECK (quantity > 0),
        PRIMARY KEY (reservation_id, equipment_id)
      );

      INSERT INTO sports VALUES ('badminton','Бадминтон'), ('table-tennis','Настольный теннис'), ('volleyball','Волейбол'),
        ('basketball','Баскетбол'), ('football','Футбол'), ('tennis','Теннис');
      INSERT INTO halls VALUES ('hall-1','Зал №1'), ('hall-2','Зал №2');
      INSERT INTO courts (id,name,sport_id,hall_id,image,capacity,description,dimensions,surface,equipment_description) VALUES
        (1,'Площадка №1','badminton','hall-1','/images/home/badminton.png',4,
         'Крытый корт для игры один на один или пара на пару. На полу есть разметка для обоих форматов.',
         '13,4 × 6,1 м','Спортивное покрытие ПВХ','Сетка установлена. Ракетки и воланы можно взять на стойке.'),
        (2,'Площадка №2','table-tennis','hall-2','/images/home/table-tennis.png',4,
         'Игровая зона с одним столом. Подходит для тренировки подачи, одиночной и парной игры.',
         '8 × 5 м','Спортивный линолеум','Стол с сеткой. Ракетки и мячи можно взять на стойке.'),
        (3,'Площадка №3','volleyball','hall-1','/images/home/volleyball.png',6,
         'Крытая площадка для тренировок подачи, приёма и игры небольшими командами.',
         '18 × 9 м','Спортивный паркет','Сетка установлена. Волейбольный мяч можно взять на стойке.');
      SELECT setval(pg_get_serial_sequence('courts','id'), (SELECT max(id) FROM courts));
      INSERT INTO equipment VALUES ('racket','Ракетка для бадминтона'), ('shuttle','Волан'),
        ('paddle','Ракетка для настольного тенниса'), ('table-ball','Мяч для настольного тенниса'),
        ('volley-ball','Волейбольный мяч');
      INSERT INTO court_equipment VALUES (1,'racket',4),(1,'shuttle',6),(2,'paddle',4),(2,'table-ball',6),(3,'volley-ball',2);
      INSERT INTO opening_hours
        SELECT day, CASE WHEN day IN (0,6) THEN 540 ELSE 480 END,
                    CASE WHEN day IN (0,6) THEN 1320 ELSE 1380 END
        FROM generate_series(0,6) AS day;

      ALTER TABLE court_reservations ADD CONSTRAINT court_reservations_court_fk FOREIGN KEY (court_id) REFERENCES courts(id);
      ALTER TABLE court_reservations ADD CONSTRAINT court_reservations_players_check CHECK (players IS NULL OR players > 0);
      ALTER TABLE court_reservations ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now();
      ALTER TABLE court_reservations ADD COLUMN IF NOT EXISTS equipment JSONB NOT NULL DEFAULT '[]'::jsonb;
      INSERT INTO equipment (id,name)
        SELECT DISTINCT ON (item->>'id') item->>'id', item->>'name'
        FROM court_reservations CROSS JOIN LATERAL jsonb_array_elements(equipment) AS item
        WHERE item->>'id' IS NOT NULL AND item->>'name' IS NOT NULL
        ON CONFLICT (id) DO NOTHING;
      INSERT INTO reservation_equipment (reservation_id,equipment_id,equipment_name,quantity)
        SELECT r.id, item->>'id', item->>'name', (item->>'quantity')::smallint
        FROM court_reservations r CROSS JOIN LATERAL jsonb_array_elements(r.equipment) AS item;
      ALTER TABLE court_reservations DROP COLUMN equipment;
      INSERT INTO schema_migrations (version) VALUES ('001_catalog');
    `);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}
